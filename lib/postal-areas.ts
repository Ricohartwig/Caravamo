export function postalPoint(postalCode: string | null): { lat: number; lon: number } | null {
  if (!postalCode || !/^[0-9]{5}$/.test(postalCode)) {
    return null;
  }

  const area = areas[postalCode.slice(0, 2)];
  if (!area) {
    return null;
  }

  const spread = Number(postalCode.slice(2));
  return {
    lat: area[0] + ((spread % 17) - 8) * 0.012,
    lon: area[1] + ((Math.floor(spread / 17) % 11) - 5) * 0.015,
  };
}
